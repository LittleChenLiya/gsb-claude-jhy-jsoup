package org.jsoup.outline;

import org.jsoup.nodes.Element;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 A single heading section within a {@link HeadingOutline}. Holds the heading's level, text, id (existing or
 generated), and a reference to the source {@link Element} for position information. A Section is a read-only view;
 extracting an outline never modifies the source document.
 */
public final class Section {
    private final int level;
    private final String text;
    private final String id;
    private final boolean generatedId;
    private final Element element;
    private final List<Section> children = new ArrayList<>(); // internal build buffer; never exposed directly

    Section(int level, String text, String id, boolean generatedId, Element element) {
        this.level = level;
        this.text = text;
        this.id = id;
        this.generatedId = generatedId;
        this.element = element;
    }

    /** @return the heading level, 1 ({@code h1}) through 6 ({@code h6}) */
    public int level() {
        return level;
    }

    /** @return the heading text, per {@link Element#text()} semantics */
    public String text() {
        return text;
    }

    /**
     The heading's id: the element's existing {@code id} attribute if present, otherwise a stable generated
     identifier ({@code outline-N}) that exists only in this report and was not written to the DOM.
     @return the id of this section
     @see #hasGeneratedId()
     */
    public String id() {
        return id;
    }

    /** @return true if {@link #id()} was generated by the outline extraction (the source element has no id) */
    public boolean hasGeneratedId() {
        return generatedId;
    }

    /** @return the source heading element, for position and further inspection; never modified by the extraction */
    public Element element() {
        return element;
    }

    /**
     The direct child sections of this section.
     @return an independent unmodifiable copy of the child list; it shares no mutable container with the outline,
     so neither this section nor the outline can be altered through it
     */
    public List<Section> children() {
        return Collections.unmodifiableList(new ArrayList<>(children));
    }

    /** Adds a child during outline construction. */
    void addChild(Section child) {
        children.add(child);
    }

    @Override public String toString() {
        return "h" + level + " #" + id + (generatedId ? " (generated id)" : "") + ": " + text;
    }
}
